# 辺を 2 つに割る（2 段）と 3 つに割る（3 段）：中心→角（電子）と、中心→角の小さな正四面体の中心（H）。整数だけ
d2=lambda a:sum(x*x for x in a)
for n in (2,3):
    k=3*n                                    # 大きな正四面体の角 (k,k,k) など。小さな正四面体の辺² は 72 のまま
    corner=(k,k,k)
    sub=[(k,k,k),(k,k-6,k-6),(k-6,k,k-6),(k-6,k-6,k)]       # 角の小さな正四面体
    c=tuple(sum(v[i] for v in sub)//4 for i in range(3))
    R2,h2=d2(corner),d2(c)
    print(n,"つに割る：大きな辺²",2*(2*k)**2,"／ 中心→角",R2,"／ 中心→小さな正四面体の中心",h2,
          "／ 長さの比の 2 乗：",h2,"×",n*n,"＝",h2*n*n,"、",R2,"×",(n-1)**2,"＝",R2*(n-1)**2,"→ 一致" if h2*n*n==R2*(n-1)**2 else "")
