# 次元によらない判定：内積だけ（3 次元の単位、整数）
# 3 つの環が同じ C10 に届くには、a→b の向き d が 3 つの環でそろう必要がある（C10 − C9 ＝ 2d）
u2,uu=27,-9          # C9 から a へ：長さ² 27、互いの内積 −9（C9 の正四面体）
d2=36                # a から b へ（帯の隣どうし、長さ² 36）
ud=18                # C9→a と a→b の内積（星型正八面体の中で決まる値の符号を合わせたもの）
for k in (2,3):
    s=u2+(k-1)*uu; sumsq=k*u2+k*(k-1)*uu
    lhs=ud*ud*sumsq; rhs=d2*s*s
    print("環",k,"個：d の、u の張る空間への成分の長さ²×",s*s,"＝",lhs,"／ d の長さ²×",s*s,"＝",rhs,"→",
          "ちょうど一致（閉じる）" if lhs==rhs else ("成分が d より長い：どの次元でも閉じない" if lhs>rhs else "残りを別の次元へ逃がせば閉じる"))
